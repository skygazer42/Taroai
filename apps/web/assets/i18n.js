  function translateElement(element) {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      const value = element.getAttribute?.(attribute);
      const translated = t(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
    if (element.matches?.(contentSelector)) return;
    for (const child of element.childNodes || []) {
      if (child.nodeType !== Node.TEXT_NODE || child.parentElement?.closest(contentSelector)) continue;
      const translated = t(child.nodeValue);
      if (translated !== child.nodeValue) child.nodeValue = translated;
    }
    for (const child of element.children || []) translateElement(child);
  }

  function setLocale(nextLocale) {
    if (nextLocale !== "zh-CN" && nextLocale !== "en") return;
    localStorage.setItem("taroai.locale", nextLocale);
    window.location.reload();
  }

  window.TaroaiI18n = { locale, setLocale, t, localize: translateElement };
  if (locale !== "zh-CN") return;
  translateElement(document.documentElement);
  new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "attributes") translateElement(record.target);
      for (const node of record.addedNodes) {
        if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
        else if (node.nodeType === Node.TEXT_NODE && !node.parentElement?.closest(contentSelector)) {
          node.nodeValue = t(node.nodeValue);
        }
      }
    }
  }).observe(document.body, {
    subtree: true,
    childList: true,
    attributes: true,
    attributeFilter: ["aria-label", "placeholder", "title"],
  });
