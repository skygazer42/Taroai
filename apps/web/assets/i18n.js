  function t(value) {
    if (locale !== "zh-CN" || typeof value !== "string") return value;
    const exact = zh.get(value.trim());
    if (exact) return value.replace(value.trim(), exact);
    for (const [pattern, render] of dynamic) {
      const match = value.trim().match(pattern);
      if (match) return value.replace(value.trim(), render(...match));
    }
    return value;
  }

